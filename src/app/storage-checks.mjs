export async function runStorageChecks(app) {
  const $ = id => document.getElementById(id), checks = [];
  const check = (name, passed) => checks.push({ name, passed: Boolean(passed) });
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const until = async predicate => { for (let i = 0; i < 100; i++) { if (predicate()) return true; await wait(25); } return false; };
  const shortcut = (key, shiftKey = false) => document.dispatchEvent(new KeyboardEvent('keydown', { key, ctrlKey: true, shiftKey, bubbles: true, cancelable: true }));
  const input = value => { $('source').value = value; $('source').setSelectionRange(value.length, value.length); $('source').dispatchEvent(new InputEvent('input', { bubbles: true })); };
  const sourceMode = () => { app.setLayout('single'); $('source-mode').click(); };
  const testFile = request => window.workspaceFiles.testFiles(request);
  const read = item => window.workspaceFiles.read(item.file.id);
  app.setLayout('single'); shortcut('n'); sourceMode();
  const item = app.current();
  input('# 保存验证\n\n中文正文。\n'); shortcut('s');
  check('Ctrl+S 为未命名文档选择位置并实际保存', await until(() => item.file && !item.saving) && (await read(item)).content === '# 保存验证\n\n中文正文。\n');
  check('保存后清除未保存标记', !app.isDirty(item) && !document.title.startsWith('●'));
  shortcut('z'); check('保存后仍可撤销，撤销后相对磁盘重新标记修改', app.isDirty(item));
  shortcut('y'); check('重做回到已保存内容时清除修改标记', !app.isDirty(item));
  app.setLayout('sync');
  $('right-source').dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }));
  $('right-source').value += '\n右侧源码修改并保存。\n';
  $('right-source').dispatchEvent(new InputEvent('input', { bubbles: true }));
  shortcut('s'); await until(() => !item.saving);
  check('同步模式保存右侧编辑内容到同一磁盘文件', (await read(item)).content.includes('右侧源码修改并保存') && !app.isDirty(item));
  const savedId = item.file.id;
  await app.closeDocuments([item.key]); await app.openWorkspaceFile(savedId);
  check('关闭后重新读取磁盘文件，内容保持一致', app.current().history.current.markdown.includes('右侧源码修改并保存'));
  sourceMode();
  const current = app.current(), diskBefore = (await read(current)).content;
  input(diskBefore + '\n等待写入的版本\n');
  await testFile({ action: 'delay', delay: 150 });
  const saving = app.saveDocument(current);
  input(diskBefore + '\n保存过程中继续输入\n'); await saving;
  check('保存期间继续编辑不会被误标为已保存', app.isDirty(current) && (await read(current)).content.includes('等待写入的版本') && $('source').value.includes('继续输入'));
  await testFile({ action: 'delay', delay: 0 }); await app.saveDocument(current);
  check('再次保存写入后续输入并更新基线', !app.isDirty(current) && (await read(current)).content.includes('保存过程中继续输入'));

  await testFile({ action: 'readonly', key: current.file.key }); input('只读文件中的未保存内容');
  check('保存失败保留编辑内容、未保存标记和错误提示', !await app.saveDocument(current) && app.isDirty(current) && $('source').value.includes('未保存内容') && $('status').textContent.includes('保存失败'));
  const closing = app.closeDocuments([current.key]); $('close-save').click();
  check('关闭前保存失败时不关闭文档', !await closing && app.documents().includes(current));
  await testFile({ action: 'writable', key: current.file.key }); await app.saveDocument(current);

  await testFile({ action: 'write', key: current.file.key, content: '# 外部改写\n' });
  await app.scanExternalFiles();
  check('无未保存修改时自动载入外部新内容', current.history.current.markdown === '# 外部改写\n' && !app.isDirty(current));
  input('# 我的本地修改\n');
  await testFile({ action: 'write', key: current.file.key, content: '# 外部再次修改\n' });
  const conflicted = app.saveDocument(current);
  check('保存检测外部修改并显示冲突选项', await until(() => $('file-conflict').open));
  $('conflict-cancel').click(); await conflicted;
  check('取消冲突处理保留本地和磁盘两个版本', current.history.current.markdown === '# 我的本地修改\n' && (await read(current)).content === '# 外部再次修改\n');
  const oldFile = current.file;
  const resolveConflict = app.saveDocument(current); await until(() => $('file-conflict').open); $('conflict-save-as').click(); await resolveConflict;
  check('冲突时另存为保留原磁盘版本和本地编辑', current.file.key !== oldFile.key && (await window.workspaceFiles.read(oldFile.id)).content === '# 外部再次修改\n' && (await read(current)).content === '# 我的本地修改\n');
  await testFile({ action: 'delete', key: current.file.key });
  const missingKey = current.file.key; input('# 原文件删除后的内容\n'); await app.saveDocument(current);
  check('原文件删除后通过另存为保留内容', current.file.key !== missingKey && (await read(current)).content.includes('原文件删除后'));
  sourceMode(); input('# 冲突时选择重新载入\n');
  await testFile({ action: 'write', key: current.file.key, content: '# 磁盘确认版本\n' });
  const reloadChoice = app.saveDocument(current); await until(() => $('file-conflict').open); $('conflict-reload').click(); await reloadChoice;
  check('冲突时明确重新载入会采用磁盘内容并更新保存基线', current.history.current.markdown === '# 磁盘确认版本\n' && !app.isDirty(current));
  const crlfFile = await window.workspaceFiles.createMarkdown({ directoryId: 'nested', name: `换行验证-${Date.now()}.md` });
  await testFile({ action: 'write', key: crlfFile.key, content: '# CRLF 标题\r\n\r\n正文\r\n' });
  await app.openWorkspaceFile(crlfFile.id);
  const crlf = app.current(), visual = document.querySelector('#rich .vditor-wysiwyg > .vditor-reset');
  visual.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })); visual.focus();
  const range = document.createRange(); range.selectNodeContents(visual.querySelector('p')); range.collapse(false);
  getSelection().removeAllRanges(); getSelection().addRange(range); document.execCommand('insertText', false, '可视追加');
  await wait(350); await app.saveDocument(crlf);
  const crlfSaved = (await read(crlf)).content;
  check('可视编辑保存保留原 Markdown 的 CRLF 换行', crlfSaved.includes('可视追加') && crlfSaved.includes('\r\n') && !/(?<!\r)\n/.test(crlfSaved));

  await app.openWorkspaceFile('main.js'); sourceMode();
  const code = app.current(), originalCode = (await read(code)).content;
  input(originalCode + '\n// 保存代码文件\n'); shortcut('s', true);
  check('Ctrl+Shift+S 另存为保留代码扩展名及原文件', await until(() => code.file.id.includes('另存-') && !code.saving) && code.kind === 'text' && code.name.endsWith('.js') && (await window.workspaceFiles.read('main.js')).content === originalCode);
  shortcut('n'); sourceMode(); const untitled = app.current(); input('取消保存位置也必须保留的内容');
  await testFile({ action: 'cancel-save' });
  check('取消保存位置不会关闭或丢弃新文档', !await app.saveDocument(untitled) && !untitled.file && app.isDirty(untitled));
  await app.flushRecovery();
  const drafts = await window.workspaceFiles.readRecovery();
  check('未命名编辑内容和保存基线真实写入恢复草稿', drafts.some(entry => entry.key === untitled.key && entry.content.includes('取消保存位置') && entry.savedText === ''));
  const discarded = app.closeDocuments([untitled.key]); $('close-discard').click(); await discarded;
  app.restoreDrafts(drafts); sourceMode();
  check('恢复草稿可重建未命名文档并继续编辑', app.current().key === untitled.key && $('source').value.includes('取消保存位置') && app.isDirty(app.current()));
  const restored = app.current(); await app.saveDocument(restored);
  check('恢复后的内容可正常保存，已保存草稿不再保留', !app.isDirty(restored) && !(await window.workspaceFiles.readRecovery()).some(entry => entry.key === restored.key));
  input('关闭前应该保存的内容');
  const beforeClose = restored.file.id;
  const saveClose = app.closeDocuments([restored.key]); $('close-save').click();
  check('关闭选择保存后写入磁盘并关闭标签页', await saveClose && !app.documents().includes(restored) && (await window.workspaceFiles.read(beforeClose)).content === '关闭前应该保存的内容');

  shortcut('n'); sourceMode(); input('窗口关闭保护');
  await testFile({ action: 'close-window' });
  check('点击系统窗口关闭同样触发未保存提示', await until(() => $('close-confirm').open));
  $('close-cancel').click(); await wait(40);
  check('取消系统窗口关闭保留文档与内容', app.current().history.current.markdown === '窗口关闭保护' && (await testFile({ action: 'close-count' })).count === 0);
  const allClosed = app.closeDocuments(app.documents().map(entry => entry.key));
  if ($('close-confirm').open) $('close-discard').click(); await allClosed;
  check('明确放弃内容后清除恢复草稿', (await window.workspaceFiles.readRecovery()).length === 0);
  await app.openWorkspaceFile(savedId); app.setLayout('sync');
  await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  return { checks };
}
