const wait = ms => new Promise(resolve => setTimeout(resolve, ms));

export async function runUXChecks() {
  const checks = [];
  const observations = {};
  const check = (name, passed) => checks.push({ name, passed: Boolean(passed) });
  const example = name => [...document.querySelectorAll('#examples button')].find(button => button.textContent.includes(name));
  example('长文样本').click();
  await wait(100);
  const root = document.querySelector('.vditor-wysiwyg > .vditor-reset');
  const content = document.querySelector('.vditor-content');
  observations.width = { editor: root.getBoundingClientRect().width, available: content.clientWidth };
  check('宽窗口的编辑滚动区域占满可用正文区域', root.getBoundingClientRect().width >= content.clientWidth - 4);
  observations.sidebarFont = getComputedStyle(document.querySelector('#file-tree button')).fontSize;
  check('文件目录字体至少为 14px', parseFloat(observations.sidebarFont) >= 14);
  check('标签页提供可访问的关闭按钮', document.querySelector('#tabs button[aria-label^="关闭 "]'));
  check('链接目标展示区存在', document.getElementById('link-target'));

  const heading = root.querySelectorAll('h2')[30];
  const range = document.createRange(); range.selectNodeContents(heading); range.collapse(true);
  getSelection().removeAllRanges(); getSelection().addRange(range);
  heading.click();
  await wait(350);
  const menuBeforeNavigation = getComputedStyle(root.nextElementSibling).display;
  document.getElementById('outline-tab').click();
  [...document.querySelectorAll('#outline button')].find(button => button.textContent === heading.textContent).click();
  await wait(350);
  const popover = root.nextElementSibling;
  observations.outline = { headingTop: heading.getBoundingClientRect().top, paneTop: root.getBoundingClientRect().top, popoverBeforeNavigation: menuBeforeNavigation, popoverDisplay: getComputedStyle(popover).display };
  check('大纲跳转为标题留出顶部空间并隐藏旧浮动菜单', menuBeforeNavigation !== 'none' && heading.getBoundingClientRect().top >= root.getBoundingClientRect().top + 35 && getComputedStyle(popover).display === 'none');

  example('开始写作').click();
  check('从长文跳转切回另一文档时恢复该文档位置', root.querySelector('h1').getBoundingClientRect().top >= root.getBoundingClientRect().top + 35);
  const cell = root.querySelector('td');
  const cellRange = document.createRange(); cellRange.selectNodeContents(cell); cellRange.collapse(true);
  getSelection().removeAllRanges(); getSelection().addRange(cellRange);
  cell.click(); await wait(350);
  const action = popover.querySelector('[data-type="remove"]');
  observations.tableActionHeight = action?.getBoundingClientRect().height ?? 0;
  check('表格浮动菜单操作高度至少为 30px', observations.tableActionHeight >= 30);

  const until = async predicate => {
    for (let i = 0; i < 80; i++) { if (predicate()) return true; await wait(25); }
    return false;
  };
  const file = id => document.querySelector(`#file-tree button[data-file-id="${id}"]`);
  const tab = name => [...document.querySelectorAll('#tabs .tab-select')].find(button => button.textContent.startsWith(name));
  const openLinks = async () => { file('links.md').click(); return until(() => root.querySelector('h1')?.textContent === '链接样本' && !document.getElementById('rich').hidden); };
  document.getElementById('files-tab').click();
  await openLinks();
  let local = root.querySelector('a[href="notes.txt"]');
  const linkRect = local.getBoundingClientRect();
  const mouse = { clientX: Math.round(linkRect.left + 8), clientY: Math.round(linkRect.top + linkRect.height / 2) };
  local.dispatchEvent(new MouseEvent('mouseover', { bubbles: true, ...mouse }));
  await until(() => !document.getElementById('link-target').hidden);
  const tooltip = document.getElementById('link-target');
  const tooltipRect = tooltip.getBoundingClientRect();
  check('悬停链接时在鼠标右下方显示实际路径', tooltip.textContent.endsWith('notes.txt') && tooltip.textContent.includes('workspace-fixture') && tooltipRect.left >= mouse.clientX + 8 && tooltipRect.left <= mouse.clientX + 24 && tooltipRect.top >= mouse.clientY + 8 && tooltipRect.top <= mouse.clientY + 30);
  local.dispatchEvent(new MouseEvent('mousemove', { bubbles: true, clientX: mouse.clientX + 4, clientY: mouse.clientY + 2 }));
  const moved = tooltip.getBoundingClientRect();
  check('指针在链接内移动时地址浮层跟随移动', Math.abs(moved.left - tooltipRect.left - 4) < 1 && Math.abs(moved.top - tooltipRect.top - 2) < 1);
  local.dispatchEvent(new MouseEvent('mouseout', { bubbles: true, relatedTarget: root }));
  const external = root.querySelector('a[href^="https://"]');
  external.dispatchEvent(new MouseEvent('mouseover', { bubbles: true, ...mouse }));
  external.dispatchEvent(new MouseEvent('mouseout', { bubbles: true, relatedTarget: root }));
  await wait(80);
  check('离开链接后隐藏浮层且异步响应不会使其重新显示', tooltip.hidden);
  local.dispatchEvent(new MouseEvent('mouseover', { bubbles: true, ...mouse }));
  await until(() => !tooltip.hidden);
  local.dispatchEvent(new MouseEvent('mousemove', { bubbles: true, clientX: innerWidth - 6, clientY: innerHeight - 6 }));
  const nearEdge = tooltip.getBoundingClientRect();
  check('窗口边缘的地址浮层调整位置并保持在可视范围', nearEdge.right <= innerWidth - 8 && nearEdge.bottom <= innerHeight - 8 && nearEdge.left >= 8 && nearEdge.top >= 8);
  check('地址浮层不位于状态栏且不会阻挡鼠标操作', !tooltip.closest('footer') && getComputedStyle(tooltip).pointerEvents === 'none');
  root.dispatchEvent(new Event('scroll'));
  check('正文滚动时收起地址浮层', tooltip.hidden);
  local.dispatchEvent(new MouseEvent('mouseover', { bubbles: true, ...mouse }));
  await until(() => !tooltip.hidden);
  local.click();
  await until(() => document.getElementById('source').value.includes('纯文本标题') && !document.getElementById('source').hidden);
  check('悬停提示不影响点击链接在工具内打开本地文本', !document.getElementById('source').hidden && document.getElementById('source').value.includes('**不是加粗**'));
  await openLinks();
  root.querySelector('a[href^="nested/"]').click();
  check('含 URL 编码的中文相对路径在工具内打开', await until(() => document.getElementById('source').value.startsWith('带 BOM 的中文文本')));
  await openLinks();
  root.querySelector('a[href="../outside.txt"]').click();
  check('明确点击的父目录文本链接在工具内打开', await until(() => document.getElementById('source').value.startsWith('路径范围检查样本')));
  await openLinks();
  root.querySelector('a[href^="https://"]').click();
  check('网络链接交给默认浏览器而不替换编辑页面', await until(() => document.getElementById('status').textContent.includes('默认浏览器')) && root.querySelector('h1')?.textContent === '链接样本');
  root.querySelector('a[href="#目标标题"]').click();
  await wait(100);
  const anchorHeading = [...root.querySelectorAll('h2')].find(node => node.textContent === '目标标题');
  observations.anchor = { top: anchorHeading.getBoundingClientRect().top, bottom: anchorHeading.getBoundingClientRect().bottom, paneTop: root.getBoundingClientRect().top, paneBottom: root.getBoundingClientRect().bottom };
  check('文档内标题链接跳转保留顶部空间', anchorHeading.getBoundingClientRect().top >= root.getBoundingClientRect().top + 35 && anchorHeading.getBoundingClientRect().bottom <= root.getBoundingClientRect().bottom);
  const blocked = await window.workspaceFiles.describeLink({ href: 'javascript:alert(1)' });
  check('不将脚本协议链接交给系统执行', blocked?.error);

  file('README.MD').click(); await until(() => root.querySelector('h1')?.textContent === '文件夹里的 Markdown');
  document.getElementById('source-mode').click();
  const source = document.getElementById('source');
  source.value += '\n快捷键检查\n'; source.dispatchEvent(new InputEvent('input', { bubbles: true }));
  const edited = source.value;
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'z', ctrlKey: true, bubbles: true }));
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'z', ctrlKey: true, shiftKey: true, bubbles: true }));
  check('Ctrl+Shift+Z 保留重做行为而不切换编辑模式', source.value === edited && !source.hidden);
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'm', ctrlKey: true, shiftKey: true, bubbles: true }));
  check('Ctrl+Shift+M 仍可切换 Markdown 源码模式', source.hidden);

  const closeClean = document.querySelector('#tabs button[aria-label="关闭 custom.xyz"]');
  closeClean.click(); await wait(50);
  check('关闭按钮移除标签页而不删除目录文件', !tab('custom.xyz') && file('custom.xyz'));
  tab('notes.txt').click();
  document.querySelector('#tabs button[aria-label="关闭 notes.txt"]').click();
  check('关闭有修改的标签页先显示确认框', document.getElementById('close-confirm').open);
  document.getElementById('close-cancel').click(); await wait(50);
  check('取消关闭后标签页和修改仍保留', tab('notes.txt') && source.value.includes('本次窗口中的修改'));
  document.querySelector('#tabs button[aria-label="关闭 notes.txt"]').click();
  document.getElementById('close-discard').click(); await wait(50);
  check('确认放弃后可关闭有修改的标签页', !tab('notes.txt'));

  tab('README.MD').dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 500, clientY: 90 }));
  const menu = document.getElementById('tab-menu');
  check('标签页右键菜单包含批量关闭及路径操作', !menu.hidden && ['关闭', '关闭其他标签页', '关闭右侧标签页', '关闭全部标签页', '复制完整路径', '在文件夹中显示'].every(label => [...menu.querySelectorAll('button')].some(button => button.textContent === label)));
  [...menu.querySelectorAll('button')].find(button => button.textContent === '关闭全部标签页').click();
  if (document.getElementById('close-confirm').open) document.getElementById('close-discard').click();
  await wait(50);
  check('关闭全部标签页后显示可继续打开文件的空状态', document.querySelectorAll('#tabs .document-tab').length === 0 && !document.getElementById('empty-state').hidden);
  file('README.MD').click();
  check('关闭全部后仍可从目录重新打开文件', await until(() => Boolean(tab('README.MD'))));
  await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  await wait(100);
  return { checks, observations };
}
